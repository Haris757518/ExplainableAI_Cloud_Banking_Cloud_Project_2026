import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8012');
await page.getByRole('heading',{name:'Real Banking Performance',exact:true}).waitFor();
await page.getByText('2,482 published records in selection').waitFor();
if(await page.locator('.primary-nav button').count()!==2)throw Error('Expected exactly two primary modes');
await page.getByLabel('Service',{exact:true}).selectOption('Open Banking Payment Initiation');
await page.getByRole('button',{name:'Analyze selected history'}).click();
await page.getByText('3 model-flagged deviations on the untouched final period.').waitFor();
await page.screenshot({path:'results/redesign_20261022/dashboard.png',fullPage:true});
await page.getByLabel('Bank',{exact:true}).selectOption('starling');
await page.getByText('28,306 records').waitFor();
await page.getByLabel('Service',{exact:true}).selectOption('Payment Initiation (Open Banking)');
await page.getByRole('button',{name:'Analyze selected history'}).click();
await page.getByText('0 model-flagged deviations on the untouched final period.').waitFor();
await page.getByRole('button',{name:'AI Research & Validation',exact:true}).click();
await page.getByRole('button',{name:'Measured research results',exact:true}).click();
await page.getByRole('heading',{name:'Compatible Alibaba graph comparison'}).waitFor();
await page.screenshot({path:'results/redesign_20261022/research.png',fullPage:true});
if(errors.length)throw Error(errors.join('\n'));
console.log('Browser acceptance passed: two modes, Monzo/Starling analysis, research comparison, no page errors');
await browser.close();
